create or replace function public.week_registration_is_open(p_week_id uuid)
returns boolean
language sql
stable
security definer
set search_path=public
as $$
  with target as (
    select id,school_year_id,week_number,start_date,status
    from public.weeks
    where id=p_week_id
  ),
  clock as (
    select (now() at time zone 'Asia/Ho_Chi_Minh')::date as today
  ),
  anchor as (
    select w.week_number
    from public.weeks w
    join target t on t.school_year_id=w.school_year_id
    cross join clock c
    where c.today between w.start_date and (w.start_date + 6)
    order by w.week_number
    limit 1
  )
  select coalesce(
    t.status <> 'holiday'
    and a.week_number is not null
    and t.week_number between a.week_number and (a.week_number + 1),
    false
  )
  from target t
  left join anchor a on true
$$;

