-- Emergency luôn chuyển GV duyệt, không auto-rule/AI.
create or replace function public.apply_smart_approval()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_enabled boolean := public.smart_approval_is_enabled();
  v_ai_enabled boolean := public.ai_review_is_enabled();
  v_route text;
  v_reason text;
  v_should_review boolean := false;
begin
  if auth.uid()=new.student_id and new.status='approved' then
    new.status:='submitted';
    new.approval_source:='manual';
    new.approved_at:=null;
    new.approved_by:=null;
  end if;

  if new.status='submitted' then
    if tg_op='INSERT' then
      v_should_review:=true;
    elsif old.status is distinct from 'submitted'
       or old.content is distinct from new.content
       or old.note is distinct from new.note then
      v_should_review:=true;
    end if;
  end if;

  if v_should_review then
    new.ai_decision:=null;
    new.ai_category:=null;
    new.ai_confidence:=null;
    new.ai_reason:=null;
    new.ai_model:=null;
    new.ai_reviewed_at:=null;

    if coalesce(new.is_emergency,false) then
      new.status:='submitted';
      new.approval_source:='manual';
      new.auto_review_reason:='Đăng ký bổ sung khẩn cấp sau deadline; giáo viên cần duyệt.';
      new.ai_review_status:='not_needed';
      new.approved_at:=null;
      new.approved_by:=null;

    elsif not v_enabled then
      new.status:='submitted';
      new.approval_source:='manual';
      new.auto_review_reason:='Duyệt nhanh thông minh đang tắt.';
      new.ai_review_status:='not_needed';
      new.approved_at:=null;
      new.approved_by:=null;

    else
      select r.route,r.reason into v_route,v_reason
      from public.smart_review_route(new.content,new.note) r;

      new.auto_review_reason:=v_reason;

      if v_route='auto_rule' then
        new.status:='approved';
        new.approval_source:='auto_rule';
        new.ai_review_status:='not_needed';
        new.approved_at:=now();
        new.approved_by:=null;

      elsif v_route='ai' and v_ai_enabled then
        new.status:='submitted';
        new.approval_source:='manual';
        new.ai_review_status:='pending';
        new.approved_at:=null;
        new.approved_by:=null;

      else
        new.status:='submitted';
        new.approval_source:='manual';
        new.ai_review_status:='not_needed';
        new.approved_at:=null;
        new.approved_by:=null;
      end if;
    end if;

  elsif new.status='approved' and auth.uid() is distinct from new.student_id then
    if new.approval_source not in ('auto_rule','ai') then
      new.approval_source:='manual';
    end if;
  end if;

  return new;
end;
$$;

-- Notification rõ riêng trường hợp khẩn cấp.
create or replace function public.sync_teacher_review_notification()
returns trigger
language plpgsql
security definer
set search_path=public
as $$
declare
  v_student_name text;
  v_reason text;
begin
  select full_name into v_student_name
  from public.profiles
  where id=new.student_id;

  v_reason:=coalesce(new.ai_reason,new.auto_review_reason,'');

  if new.status='submitted'
     and new.approval_source='manual'
     and new.ai_review_status not in ('pending','processing')
  then
    insert into public.teacher_notifications(
      registration_id,student_id,week_id,notification_type,title,message,is_read,created_at
    )
    values(
      new.id,new.student_id,new.week_id,'manual_review',
      case
        when coalesce(new.is_emergency,false) then '🚨 Đăng ký bổ sung khẩn cấp'
        when new.ai_review_status='completed' then 'AI đề nghị giáo viên duyệt'
        when new.ai_review_status='error' then 'AI chưa xử lý được — cần giáo viên duyệt'
        else 'Đăng ký cần giáo viên duyệt'
      end,
      coalesce(v_student_name,'Học sinh') || ': ' ||
      left(coalesce(new.content,''),160) ||
      case
        when coalesce(new.is_emergency,false) and coalesce(new.emergency_reason,'')<>''
          then ' — Lý do bổ sung: '||left(new.emergency_reason,180)
        when v_reason<>'' then ' — '||v_reason
        else ''
      end,
      false,now()
    )
    on conflict (registration_id,notification_type)
    do update set
      title=excluded.title,
      message=excluded.message,
      is_read=false,
      created_at=now();
  else
    update public.teacher_notifications
    set is_read=true
    where registration_id=new.id
      and notification_type='manual_review'
      and is_read=false;
  end if;

  return new;
end;
$$;

