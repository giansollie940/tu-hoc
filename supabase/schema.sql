begin
  if not exists (
    select 1
    from information_schema.columns
    where table_schema='public'
      and table_name='weeks'
      and column_name='deadline_mode'
  ) then
    alter table public.weeks
      add column deadline_mode text not null default 'week_before_20';

    -- Bảo toàn hành vi V4: deadline đang có được coi là "hạn cụ thể"
    -- cho tới khi GV chủ động đổi chế độ của tuần đó.
    update public.weeks
    set deadline_mode='specific'
    where registration_deadline is not null;
  end if;
end $$;

