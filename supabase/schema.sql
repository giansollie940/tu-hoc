-- Deadline thực tế của một tiết.
-- p_weekday: 1=Thứ 2 ... 5=Thứ 6.
create or replace function public.registration_deadline_for_slot (p_week_id uuid, p_weekday int) returns timestamptz language sql stable security definer
set
  search_path = public as $$
  select
    case w.deadline_mode
      when 'per_session_20' then
        (
          (
            w.start_date
            + (greatest(1, least(5, p_weekday)) - 1)
            - 1
          )::timestamp
          + time '20:00'
        ) at time zone 'Asia/Ho_Chi_Minh'
      when 'week_before_20' then
        (
          (w.start_date - 1)::timestamp
          + time '20:00'
        ) at time zone 'Asia/Ho_Chi_Minh'
      when 'specific' then
        w.registration_deadline
      else
        w.registration_deadline
    end
  from public.weeks w
  where w.id = p_week_id
$$;

