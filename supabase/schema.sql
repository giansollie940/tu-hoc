    return query select 'manual'::text, 'Có dấu hiệu giải trí/mạng xã hội; giữ lại để giáo viên duyệt.'::text;
    return;
  end if;

  if v_has_device and v_is_specific_study then
    return query select 'auto_rule'::text, 'Thiết bị điện tử đi kèm mục đích học tập rất rõ.'::text;
    return;
  end if;

  if not v_has_device and v_is_specific_study then
    return query select 'auto_rule'::text, 'Nội dung học tập đủ cụ thể để duyệt theo quy tắc.'::text;
    return;
  end if;

  -- Có tín hiệu học nhưng cách diễn đạt chưa đủ cụ thể, hoặc có thiết bị:
  -- để AI đọc ngữ nghĩa thay vì dựa hoàn toàn vào từ khóa.
  if v_has_study or v_has_device then
    return query select 'ai'::text, 'Nội dung có khả năng liên quan học tập nhưng cần AI đọc ngữ cảnh.'::text;
    return;
  end if;

  return query select 'ai'::text, 'Nội dung chưa rõ; chuyển AI phân loại ngữ nghĩa.'::text;
end;
$$;

