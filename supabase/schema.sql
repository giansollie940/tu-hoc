-- Phân loại bảo thủ:
-- - Có tín hiệu giải trí / mạng xã hội => GV duyệt.
-- - Có tín hiệu học tập rõ ràng => tự duyệt.
-- - Thiết bị điện tử chỉ tự duyệt khi đi kèm mục đích học.
-- - Còn lại => GV duyệt.
create or replace function public.smart_review_registration (p_content text, p_note text) returns table (auto_approve boolean, reason text) language plpgsql stable security definer
set
  search_path = public as $$
declare
  v_text text := lower(coalesce(p_content,'') || ' ' || coalesce(p_note,''));
  v_has_study boolean;
  v_has_device boolean;
  v_has_nonstudy boolean;
begin
  v_has_nonstudy :=
    v_text ~ '(chơi[[:space:]]*game|game[[:space:]]*giải[[:space:]]*trí|tiktok|facebook|instagram|xem[[:space:]]*phim|video[[:space:]]*giải[[:space:]]*trí|nghe[[:space:]]*nhạc|mạng[[:space:]]*xã[[:space:]]*hội|lướt[[:space:]]*mạng|chat|nhắn[[:space:]]*tin|giải[[:space:]]*trí|shopping|mua[[:space:]]*sắm)';

  v_has_device :=
    v_text ~ '(điện[[:space:]]*thoại|laptop|máy[[:space:]]*tính|tablet|ipad|chromebook|thiết[[:space:]]*bị[[:space:]]*điện[[:space:]]*tử|internet|website|youtube|ứng[[:space:]]*dụng|app)';

  v_has_study :=
    v_text ~ '(học|ôn|ôn[[:space:]]*tập|bài[[:space:]]*tập|làm[[:space:]]*bài|đọc[[:space:]]*sách|soạn[[:space:]]*bài|luyện|làm[[:space:]]*đề|đề[[:space:]]*kiểm[[:space:]]*tra|nghiên[[:space:]]*cứu|tra[[:space:]]*cứu|tìm[[:space:]]*tài[[:space:]]*liệu|ghi[[:space:]]*chép|thuyết[[:space:]]*trình|dự[[:space:]]*án|lập[[:space:]]*trình|coding|programming|bài[[:space:]]*giảng|từ[[:space:]]*vựng|công[[:space:]]*thức|sgk|sách[[:space:]]*giáo[[:space:]]*khoa|kiểm[[:space:]]*tra|study|homework|research|practice|toán|ngữ[[:space:]]*văn|văn[[:space:]]*học|tiếng[[:space:]]*anh|anh[[:space:]]*văn|vật[[:space:]]*lí|vật[[:space:]]*lý|hóa[[:space:]]*học|hoá[[:space:]]*học|sinh[[:space:]]*học|lịch[[:space:]]*sử|địa[[:space:]]*lí|địa[[:space:]]*lý|tin[[:space:]]*học|công[[:space:]]*nghệ|giáo[[:space:]]*dục)';

  if v_has_nonstudy then
    return query select false, 'Có dấu hiệu giải trí/mạng xã hội; cần giáo viên xác nhận.';
    return;
  end if;

  if v_has_device and v_has_study then
    return query select true, 'Thiết bị điện tử được nêu kèm mục đích học tập rõ ràng.';
    return;
  end if;

  if v_has_study and not v_has_device then
    return query select true, 'Nội dung học tập rõ ràng.';
    return;
  end if;

  if v_has_device and not v_has_study then
    return query select false, 'Có sử dụng thiết bị điện tử nhưng mục đích học tập chưa đủ rõ.';
    return;
  end if;

  return query select false, 'Nội dung chưa đủ rõ để tự động duyệt.';
end;
$$;

