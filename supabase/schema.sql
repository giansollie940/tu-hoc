-- ai        = mơ hồ -> gửi AI đánh giá
create or replace function public.smart_review_route (p_content text, p_note text) returns table (route text, reason text) language plpgsql stable security definer
set
  search_path = public as $$
declare
  v_text text := lower(coalesce(p_content,'') || ' ' || coalesce(p_note,''));
  v_has_study boolean;
  v_has_device boolean;
  v_has_nonstudy boolean;
  v_is_specific_study boolean;
begin
  v_has_nonstudy :=
    v_text ~ '(chơi[[:space:]]*game|game[[:space:]]*giải[[:space:]]*trí|tiktok|facebook|instagram|xem[[:space:]]*phim|video[[:space:]]*giải[[:space:]]*trí|nghe[[:space:]]*nhạc|mạng[[:space:]]*xã[[:space:]]*hội|lướt[[:space:]]*mạng|chat|nhắn[[:space:]]*tin|giải[[:space:]]*trí|shopping|mua[[:space:]]*sắm)';

  v_has_device :=
    v_text ~ '(điện[[:space:]]*thoại|laptop|máy[[:space:]]*tính|tablet|ipad|chromebook|thiết[[:space:]]*bị[[:space:]]*điện[[:space:]]*tử|internet|website|youtube|ứng[[:space:]]*dụng|app)';

  v_has_study :=
    v_text ~ '(học|ôn|ôn[[:space:]]*tập|bài[[:space:]]*tập|làm[[:space:]]*bài|đọc[[:space:]]*sách|soạn[[:space:]]*bài|luyện|làm[[:space:]]*đề|nghiên[[:space:]]*cứu|tra[[:space:]]*cứu|tìm[[:space:]]*tài[[:space:]]*liệu|ghi[[:space:]]*chép|thuyết[[:space:]]*trình|dự[[:space:]]*án|lập[[:space:]]*trình|coding|programming|bài[[:space:]]*giảng|từ[[:space:]]*vựng|sgk|sách[[:space:]]*giáo[[:space:]]*khoa|kiểm[[:space:]]*tra|study|homework|research|practice|toán|ngữ[[:space:]]*văn|tiếng[[:space:]]*anh|vật[[:space:]]*lí|vật[[:space:]]*lý|hóa[[:space:]]*học|hoá[[:space:]]*học|sinh[[:space:]]*học|lịch[[:space:]]*sử|địa[[:space:]]*lí|địa[[:space:]]*lý|tin[[:space:]]*học)';

  -- Cụm học tập đủ cụ thể để rule tự duyệt không cần AI.
  v_is_specific_study :=
    v_text ~ '(ôn[[:space:]]*tập|làm[[:space:]]*bài|bài[[:space:]]*tập|làm[[:space:]]*đề|đọc[[:space:]]*(sgk|sách)|soạn[[:space:]]*bài|lập[[:space:]]*trình|bài[[:space:]]*giảng|tra[[:space:]]*cứu.*(toán|văn|anh|lý|lí|hóa|hoá|sinh|sử|địa|tin)|tìm[[:space:]]*tài[[:space:]]*liệu.*(học|môn|bài))';

